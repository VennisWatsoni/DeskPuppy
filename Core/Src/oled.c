#include "stm32f1xx_hal.h"
#include "oled.h"

static void SoftSPI_Delay_us(uint32_t t)
{
	uint32_t i;
	while(t--)
		for(i=0;i<36;i++);
}

//软件SPI发送1字节
void OLED_Write_Byte(uint8_t dat)
{
	uint8_t i;
	for(i=0;i<8;i++)
	{
		OLED_SCL_LOW();
		if(dat & 0x80)
			OLED_SDA_HIGH();
		else
			OLED_SDA_LOW();
		dat <<=1;
		SoftSPI_Delay_us(1);
		OLED_SCL_HIGH();
		SoftSPI_Delay_us(1);
	}
}

//写命令 DC=0
void OLED_Write_Cmd(uint8_t cmd)
{
	OLED_DC_LOW();
	OLED_Write_Byte(cmd);
}

//写数据 DC=1
void OLED_Write_Data(uint8_t data)
{
	OLED_DC_HIGH();
	OLED_Write_Byte(data);
}

void OLED_Init(void)
{
	//RES复位时序
	OLED_RES_HIGH();
	HAL_Delay(20);
	OLED_RES_LOW();
	HAL_Delay(20);
	OLED_RES_HIGH();

	OLED_Write_Cmd(0xAE); //关闭显示
	OLED_Write_Cmd(0xD5);
	OLED_Write_Cmd(0x80);
	OLED_Write_Cmd(0xA8);
	OLED_Write_Cmd(0x3F);
	OLED_Write_Cmd(0xD3);
	OLED_Write_Cmd(0x00);
	OLED_Write_Cmd(0x40);
	OLED_Write_Cmd(0xA1); //段映射
	OLED_Write_Cmd(0xC8);
	OLED_Write_Cmd(0xDA);
	OLED_Write_Cmd(0x12);
	OLED_Write_Cmd(0x81);
	OLED_Write_Cmd(0xCF);
	OLED_Write_Cmd(0xD9);
	OLED_Write_Cmd(0xF1);
	OLED_Write_Cmd(0xDB);
	OLED_Write_Cmd(0x30);
	OLED_Write_Cmd(0xA4);
	OLED_Write_Cmd(0xA6);
	OLED_Write_Cmd(0x8D);
	OLED_Write_Cmd(0x14); //电荷泵开启，3.3V供电
	OLED_Write_Cmd(0xAF); //开显示
	OLED_Clear();
}

void OLED_Clear(void)
{
	uint8_t y,x;
	for(y=0;y<8;y++)
	{
		OLED_Write_Cmd(0xb0+y);
		OLED_Write_Cmd(0x00);
		OLED_Write_Cmd(0x10);
		for(x=0;x<128;x++)
			OLED_Write_Data(0x00);
	}
}

void OLED_SetPos(uint8_t x,uint8_t y)
{
	OLED_Write_Cmd(0xb0+y);
	OLED_Write_Cmd(((x&0xf0)>>4)|0x10);
	OLED_Write_Cmd(x&0x0f);
}

