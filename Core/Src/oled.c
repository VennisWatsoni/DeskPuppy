void OLED_ShowString(uint8_t x,uint8_t y,char *str,uint8_t fontsize)
{
	while(*str)
	{
		if(fontsize == 16)
		{
			OLED_SetPos(x,y);
			OLED_Write_Data(F8X16[(*str)*16]);
			OLED_Write_Data(F8X16[(*str)*16+1]);
			OLED_SetPos(x,y+1);
			OLED_Write_Data(F8X16[(*str)*16+8]);
			OLED_Write_Data(F8X16[(*str)*16+9]);
			x += 8;
			if(x>120)
			{
				x = 0;
				y += 2;
			}
		}
		str++;
	}
}

void OLED_DrawFullImage(const uint8_t *img)
{
    uint8_t page,x;
    for(page=0;page<8;page++)
    {
        OLED_SetPos(0, page);
        for(x=0;x<128;x++)
        {
            OLED_Write_Data(*img++);
        }
    }
}
